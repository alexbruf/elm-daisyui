#!/usr/bin/env bun
// tools/gen-corpus-elm.js
//
// Bridges the JSON corpus into elm-test (SPEC.md step 6, Tier A, "CorpusTest").
//
// Reads fixtures/corpus/*.json (written by tools/extract-corpus.js) and
// fixtures/rejected.md, and writes two generated Elm modules:
//
//   tests/Corpus/Fixtures.elm  every docs example, as
//                              { id, component, title, elements }
//                              with one element per HTML element that carries
//                              at least one daisyUI ($$-prefixed) class
//   tests/Corpus/Rejected.elm  the id/reason table of fixtures/rejected.md
//
// CorpusTest then asserts that every fixture id is either accepted (has a
// hand-written tree in tests/Corpus/Trees.elm whose render matches) or
// rejected (listed in rejected.md with a reason).
//
// Both files are run through elm-format, so they read like the hand-written
// modules next to them.
//
// Run with: bun tools/gen-corpus-elm.js

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const CORPUS_DIR = path.join(ROOT, "fixtures/corpus");
const REJECTED_PATH = path.join(ROOT, "fixtures/rejected.md");
const FIXTURES_ELM = path.join(ROOT, "tests/Corpus/Fixtures.elm");
const REJECTED_ELM = path.join(ROOT, "tests/Corpus/Rejected.elm");

function elmString(value) {
  return '"' + value.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
}

function readFixtures() {
  return fs
    .readdirSync(CORPUS_DIR)
    .filter((name) => name.endsWith(".json") && name !== "index.json")
    .sort()
    .map((name) => JSON.parse(fs.readFileSync(path.join(CORPUS_DIR, name), "utf8")));
}

/**
 * Parse the markdown table of fixtures/rejected.md: rows are `| id | reason |`,
 * the header row and its `---` separator are skipped, and everything outside a
 * table (prose, headings) is ignored.
 */
function readRejected() {
  if (!fs.existsSync(REJECTED_PATH)) return [];
  const rows = [];
  for (const line of fs.readFileSync(REJECTED_PATH, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed.startsWith("|")) continue;
    const cells = trimmed.slice(1, trimmed.endsWith("|") ? -1 : undefined).split("|");
    if (cells.length < 2) continue;
    const id = cells[0].trim();
    const reason = cells.slice(1).join("|").trim();
    if (id === "" || id === "id" || /^-+$/.test(id)) continue;
    rows.push({ id, reason });
  }
  return rows;
}

function fixturesModule(fixtures) {
  const entries = fixtures.map((fixture) => {
    const elements = fixture.elements
      .filter((element) => element.daisy.length > 0)
      .map(
        (element) =>
          `        el ${elmString(element.path)} ${elmString(element.tag)} ` +
          `${elmString(element.daisy.join(" "))}`
      );
    return [
      "    { id = " + elmString(fixture.id),
      "    , component = " + elmString(fixture.component),
      "    , title = " + elmString(fixture.title),
      "    , elements =",
      elements.length === 0
        ? "        []"
        : "        [ " + elements.join("\n        , ").replace(/^ {8}/, "") + "\n        ]",
      "    }",
    ].join("\n");
  });

  return `-- GENERATED by tools/gen-corpus-elm.js. Do not edit.


module Corpus.Fixtures exposing (Element, Fixture, all)

{-| Every daisyUI docs example, as extracted into fixtures/corpus/\\*.json.

Only elements that carry at least one daisyUI class are listed: Tailwind-only
elements are layout the tree decides for itself, so \`CorpusTest\` never compares
them.

@docs Element, Fixture, all

-}


{-| One element of an example: its path in the example's element tree, its tag
and the daisyUI classes it carries.
-}
type alias Element =
    { path : String
    , tag : String
    , daisy : List String
    }


{-| One docs example.
-}
type alias Fixture =
    { id : String
    , component : String
    , title : String
    , elements : List Element
    }


el : String -> String -> String -> Element
el path tag daisy =
    { path = path, tag = tag, daisy = String.words daisy }


{-| Every example in fixtures/corpus.
-}
all : List Fixture
all =
    [ ${entries.join("\n    , ").replace(/^ {4}/, "")}
    ]
`;
}

function rejectedModule(rows) {
  const entries = rows.map(
    (row) => `{ id = ${elmString(row.id)}, reason = ${elmString(row.reason)} }`
  );
  return `-- GENERATED by tools/gen-corpus-elm.js from fixtures/rejected.md. Do not edit.


module Corpus.Rejected exposing (Rejection, all)

{-| The corpus examples the closed tree refuses, with the reason recorded in
fixtures/rejected.md.

@docs Rejection, all

-}


{-| One rejected example.
-}
type alias Rejection =
    { id : String
    , reason : String
    }


{-| Every row of the fixtures/rejected.md table.
-}
all : List Rejection
all =
    ${entries.length === 0 ? "[]" : "[ " + entries.join("\n    , ") + "\n    ]"}
`;
}

function main() {
  const fixtures = readFixtures();
  const rejected = readRejected();
  fs.mkdirSync(path.dirname(FIXTURES_ELM), { recursive: true });
  fs.writeFileSync(FIXTURES_ELM, fixturesModule(fixtures));
  fs.writeFileSync(REJECTED_ELM, rejectedModule(rejected));

  const format = Bun.spawnSync(["elm-format", "--yes", FIXTURES_ELM, REJECTED_ELM]);
  if (format.exitCode !== 0) {
    console.error(new TextDecoder().decode(format.stderr));
    process.exit(1);
  }
  const elements = fixtures.reduce(
    (total, fixture) => total + fixture.elements.filter((e) => e.daisy.length > 0).length,
    0
  );
  console.log(
    `gen-corpus-elm: ${fixtures.length} fixtures (${elements} daisyUI elements), ` +
      `${rejected.length} rejected -> tests/Corpus/Fixtures.elm, tests/Corpus/Rejected.elm`
  );
}

main();
