#!/usr/bin/env bun
// tools/gen-daisy-css.js
//
// Generates `demo/daisy-motion.css` from `Daisy.Css.stylesheet`.
//
// The package ships exactly one stylesheet: the rules behind the four
// `daisy-anim-*` classes `Daisy.Render` emits (bar grow-in, line draw-in,
// tooltip and hover-band transitions). They cannot be a daisyUI class or a
// Tailwind utility — neither library has a "grow this bar from its baseline" —
// so the package carries them itself, and it carries them *as an Elm value* for
// the same reason `alexbruf/elm-cally` does (`Cally.Css.stylesheet`, which
// `tools/gen-cally-css.js` reads the same way): the Elm registry publishes
// `src/` and nothing else, so a bare `.css` file at the repository root never
// reaches an application that installs the package.
//
// This script is the other half of that: it decodes the Elm string literal back
// into real CSS and writes the file the demo imports. `demo/daisy-motion.css` is
// committed — it is small and deterministic — but this generator stays
// authoritative, and `tools/ci.sh` regenerates it and fails on a diff, so a
// hand-edit or a stale copy is a red pipeline rather than a silent divergence.
//
// The same shape as `gen-cally-css.js`, deliberately: read an exposed
// `stylesheet : String` out of an Elm module, unescape the literal, write a
// generated file with a header naming its source.
//
// Usage: bun tools/gen-daisy-css.js

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const CSS_MODULE = join(REPO_ROOT, "src", "Daisy", "Css.elm");
const OUTPUT = join(REPO_ROOT, "demo", "daisy-motion.css");

/**
 * The body of a top-level `name = """..."""` (or `name = "..."`) declaration in
 * an Elm module, with the literal's escapes undone.
 *
 * Elm's two string forms escape the same way (`\\`, `\"`, `\n`, `\t`, `\r`,
 * `\u{XXXX}`); a triple-quoted literal simply also allows a raw newline and a
 * raw `"`. Undoing them in one pass is therefore correct for both.
 */
function elmStringDeclaration(source, name) {
  const triple = new RegExp(
    `^${name}\\s*=\\s*"""([\\s\\S]*?)"""`,
    "m"
  ).exec(source);
  const single = new RegExp(`^${name}\\s*=\\s*"((?:[^"\\\\]|\\\\.)*)"`, "m").exec(
    source
  );
  const raw = triple ? triple[1] : single ? single[1] : null;
  if (raw === null) {
    throw new Error(
      `gen-daisy-css: no top-level \`${name} = "..."\` declaration in ${CSS_MODULE}`
    );
  }
  return raw.replace(/\\(u\{([0-9a-fA-F]+)\}|.)/g, (whole, escape, code) => {
    if (code !== undefined) return String.fromCodePoint(parseInt(code, 16));
    switch (escape) {
      case "n":
        return "\n";
      case "t":
        return "\t";
      case "r":
        return "\r";
      case "\\":
        return "\\";
      case '"':
        return '"';
      case "'":
        return "'";
      default:
        throw new Error(`gen-daisy-css: unknown escape \\${escape}`);
    }
  });
}

const source = readFileSync(CSS_MODULE, "utf8");
const stylesheet = elmStringDeclaration(source, "stylesheet").trim();
const version = elmStringDeclaration(source, "version").trim();

if (!stylesheet.includes("prefers-reduced-motion")) {
  throw new Error(
    "gen-daisy-css: the stylesheet is not guarded by a prefers-reduced-motion " +
      "query. Every rule in Daisy.Css must sit inside " +
      "`@media (prefers-reduced-motion: no-preference)`."
  );
}

const header = [
  "/*",
  " * GENERATED by tools/gen-daisy-css.js. Do not edit.",
  " *",
  ` * Source: ${relative(REPO_ROOT, CSS_MODULE)} (Daisy.Css.stylesheet, version ${version})`,
  " *",
  " * The rules behind the four `daisy-anim-*` classes `Daisy.Render` emits.",
  " * Regenerate with `bun tools/gen-daisy-css.js`; `tools/ci.sh` fails on a diff.",
  " */",
  "",
].join("\n");

writeFileSync(OUTPUT, header + stylesheet + "\n");

console.log(
  `gen-daisy-css: wrote ${relative(REPO_ROOT, OUTPUT)} ` +
    `(${stylesheet.split("\n").length} lines, Daisy.Css version ${version})`
);
