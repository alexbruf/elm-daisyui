#!/usr/bin/env bun
// Reads fixtures/schema.json and writes review/src/SchemaClasses.elm, exposing
// `all : Set String` — the flat set of every daisyUI class name from the schema.
//
// This exists because elm-review rules cannot read files at runtime; the
// NoRawSchemaStrings rule (review/src/NoRawSchemaStrings.elm) needs the class
// list baked in as Elm source. Run this whenever fixtures/schema.json changes
// (i.e. whenever tools/gen-schema.js regenerates it) and before `elm-review`.
//
// Usage: bun tools/gen-review-classes.js

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const schemaPath = join(root, "fixtures", "schema.json");
const outPath = join(root, "review", "src", "SchemaClasses.elm");

const schema = JSON.parse(readFileSync(schemaPath, "utf-8"));

const all = new Set();
for (const component of Object.values(schema)) {
    for (const classes of Object.values(component)) {
        for (const cls of classes) {
            all.add(cls);
        }
    }
}

const sorted = [...all].sort();

function elmStringLiteral(s) {
    // Class names from schema.json are plain ascii identifiers (letters,
    // digits, hyphens), so a straightforward escape of quote/backslash is
    // sufficient.
    return '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
}

const listBody = sorted
    .slice(1)
    .map((c) => `    , ${elmStringLiteral(c)}`)
    .join("\n");

const contents = `-- GENERATED by tools/gen-review-classes.js from fixtures/schema.json.
-- Do not edit. Regenerate with: bun tools/gen-review-classes.js


module SchemaClasses exposing (all)

{-| Every daisyUI class name that appears anywhere in fixtures/schema.json,
flattened across all components and groups. Used by the NoRawSchemaStrings
elm-review rule to catch string literals that duplicate a schema class
outside of Daisy.Schema* / Daisy.Render.

@docs all

-}

import Set exposing (Set)


all : Set String
all =
    Set.fromList
        [ ${elmStringLiteral(sorted[0])}
${listBody}
        ]
`;

writeFileSync(outPath, contents);

// elm-format, so generated output is always format-stable (mirrors
// tools/gen-schema.js).
{
    const r = Bun.spawnSync(["elm-format", "--yes", outPath], {
        cwd: root,
        stdout: "pipe",
        stderr: "pipe",
    });
    if (r.exitCode !== 0) {
        console.error("elm-format failed:");
        console.error(new TextDecoder().decode(r.stderr));
        process.exit(1);
    }
}

console.log(
    `Wrote ${outPath} with ${sorted.length} classes (from ${schemaPath}).`
);
